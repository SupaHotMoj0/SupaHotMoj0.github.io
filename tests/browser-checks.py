def check(name, value):
    results.append({'test': name, 'passed': bool(value)})
    if not value:
        raise AssertionError(name)


def page_for(browser, width=1440, height=1000, reduced=False, touch=False, blocked=False, offline=False):
    context = browser.new_context(viewport={'width': width, 'height': height}, has_touch=touch, is_mobile=touch, reduced_motion='reduce' if reduced else 'no-preference')
    if blocked:
        context.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Blocked','SecurityError')}})")
    if offline:
        context.route('https://api.github.com/**', lambda route: route.abort())
    else:
        context.route('https://api.github.com/**', lambda route: route.fulfill(status=200, content_type='application/json', body=json.dumps(fixtures)))
    page = context.new_page()
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(BASE + '/')
    page.wait_for_selector('#pet-earth')
    page.wait_for_selector('.packet-seam')
    return context, page


def awaken(page):
    page.locator('#pet-earth').click()
    page.wait_for_timeout(850)


def open_panel(page, selector='#pet-earth'):
    page.locator(selector).dispatch_event('contextmenu', {'button': 2})
